#!/usr/bin/env python3
"""Fresh isolated full replay; frozen inputs are used read-only by workflow.

All scripts are copied; generated tables are removed before any execution.
Old anchor/restored and pinned remote columns are directory-descriptor symlinks.
No original builder is executed and no source permission is changed. This
environment maps UID/GID 0 only and lacks Landlock; OS-enforced read-only workers
cannot be created. Every frozen target SHA is verified before and after. All
executable builders and mutable captures reside in the fresh copy. Descriptor
symlinks expose only the explicitly declared input directories to the replay.
"""
from pathlib import Path
import argparse,datetime,hashlib,itertools,json,os,shutil,subprocess,sys,tempfile,time
import pandas as pd
import pyarrow.parquet as pq

ROOT=Path(__file__).resolve().parent;BASE=ROOT.parent
EXCLUDED={'statistics','__pycache__','figures','visual_check','output','outputs','caches','cache','pinned_calendar','pinned_sector_calendar','address_audit_2021_2025','results','remote_selected','remote_address_selected'}
def sha(p):
 h=hashlib.sha256()
 with open(p,'rb') as f:
  for b in iter(lambda:f.read(2**20),b''):h.update(b)
 return h.hexdigest()
def dump(p,x):p.write_text(json.dumps(x,ensure_ascii=False,indent=2,allow_nan=False)+'\n')
def ignore(path,names):return [n for n in names if n in EXCLUDED or n.endswith(('.pyc','.footer','.bin'))]
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--temp-parent',type=Path,default=Path('/workspace'));ap.add_argument('--receipt',type=Path,default=ROOT/'REPLAY.json');a=ap.parse_args()
 t=time.time();temp=Path(tempfile.mkdtemp(prefix='sgrt_full_replay_',dir=a.temp_parent));copy=temp/ROOT.name;logs=temp/'logs';logs.mkdir();(temp/'home').mkdir()
 report={'status':'RUNNING','started_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'temporary_base':str(temp),'commands':[],'comparisons':[],'worker_uid':os.getuid(),'worker_gid':os.getgid(),'os_readonly_enforcement_available':False,'input_protection':'All executable code and mutable captures copied; frozen symlinks only read; every target SHA verified before and after. UID namespace maps only 0, Landlock ENOSYS.','generated_outputs_removed_before_rebuild':True,'input_tables_really_recomputed':True,'calendar_source_rows_expected':63308662}
 dump(a.receipt,report)
 shutil.copytree(ROOT,copy,ignore=ignore)
 # Every module's root CSV/Parquet is generated by builders, not manual input.
 # Source captures/raw/source directories, law text and root typology CSV remain.
 removed=[]
 for module in ['history','medical','marketplaces','validation','agriculture']:
  for f in (copy/module).iterdir():
   if f.is_file() and (f.name.endswith(('.csv','.csv.gz','.parquet'))):removed.append(str(f.relative_to(copy)));f.unlink()
 for d in ['model/results','model/annual_results','gradients','economy/results','economy/pinned_calendar','economy/pinned_sector_calendar','economy/address_audit_2021_2025']:
  dd=copy/d
  if dd.exists():shutil.rmtree(dd)
  dd.mkdir(parents=True,exist_ok=True)
 report['removed_derived_tables']=removed
 fds=[];frozen={}
 sources=[(BASE/'anchor_research_20261019',temp/'anchor_research_20261019'),(BASE/'restored',temp/'restored'),(ROOT/'economy/remote_selected',copy/'economy/remote_selected'),(ROOT/'economy/remote_address_selected',copy/'economy/remote_address_selected')]
 for source,dest in sources:
  source=source.resolve()
  for q in source.rglob('*'):
   st=q.stat()
   if (st.st_mode&2) or st.st_uid==65534:raise RuntimeError('Frozen target is writable to replay worker: '+str(q))
   if q.is_file():frozen[str(q)]=sha(q)
  fd=os.open(source,os.O_RDONLY|os.O_DIRECTORY);fds.append(fd);dest.symlink_to(f'/proc/self/fd/{fd}',target_is_directory=True)
 report['frozen_input_file_count']=len(frozen);report['frozen_input_sha256_before']=frozen
 env=os.environ.copy();env.update({'OPENBLAS_NUM_THREADS':'1','OMP_NUM_THREADS':'1','NUMEXPR_NUM_THREADS':'1','HOME':str(temp/'home'),'MPLCONFIGDIR':str(temp/'home/matplotlib'),'PYTHONPYCACHEPREFIX':str(temp/'home/pycache'),'PYTHONPATH':os.pathsep.join(s for s in sys.path if s and Path(s).is_dir() and Path(s).name=='site-packages')})
 common={'cwd':str(temp),'env':env,'pass_fds':tuple(fds)}
 def run(label,args):
  logfile=logs/(f'{len(report["commands"]):02d}_{label}.log');start=time.time();command=[sys.executable]+[str(x) for x in args]
  with logfile.open('wb') as out:proc=subprocess.run(command,stdout=out,stderr=subprocess.STDOUT,**common)
  row={'stage':label,'command':command,'cwd':str(temp),'exit_code':proc.returncode,'seconds':round(time.time()-start,3),'log':str(logfile),'log_sha256':sha(logfile)};report['commands'].append(row);dump(a.receipt,report)
  print(label,proc.returncode,row['seconds'],flush=True)
  if proc.returncode!=0:raise RuntimeError('Replay command failed: '+label+'; see '+str(logfile))
 try:
  probe="import os,json,pandas as p; from pathlib import Path; roots=[Path('anchor_research_20261019'),Path('restored'),Path('functional_dynamics_20261019/economy/remote_selected'),Path('functional_dynamics_20261019/economy/remote_address_selected')]; assert all(x.is_symlink() for x in roots); d=p.read_parquet(roots[0]/'data/point_axis.parquet',columns=['id']); assert len(d)==142570; print(json.dumps({'uid':os.getuid(),'rows':len(d),'input_symlinks':len(roots),'input_access':'read_only_by_workflow_SHA_guard'}))"
  run('frozen_input_read_probe',['-c',probe])
  def script(label,path,*args):run(label,[copy/path,*args])
  script('history_nt','history/build_history.py');script('history_konakovo','history/build_konakovo.py');script('history_uchaly','history/build_uchaly.py')
  script('medical','medical/build_medical.py')
  script('marketplaces','marketplaces/build_marketplaces.py');script('marketplace_validation','marketplaces/validate_marketplaces.py');script('marketplace_scope','marketplaces/audit_scope_and_coverage.py')
  script('external_validation','validation/build_validation.py')
  script('integrated_graph','model/build_integrated_graph.py');script('history_accounting','model/build_history_accounting.py');script('change_evidence','model/integrate_change_evidence.py');script('center_periphery','model/centre_periphery_demography.py');script('model_invariants','model/check_invariants.py')
  script('agriculture','agriculture/build_functional_agriculture.py','--base',temp);script('agriculture_readback','agriculture/verify_outputs.py');script('crop_change','agriculture/summarize_crop_change.py')
  script('gradients','build_gradients.py')
  script('legacy_economy','economy/build_dynamics.py','--base',temp,'--out',copy/'economy/results');script('legacy_exact_summary','economy/summarize_exact_dynamics.py','--out',copy/'economy/results','--panel',temp/'restored/extracted/research/sgrt_recovered_20261019/data/panel.parquet');script('legacy_registration_size','economy/summarize_registration_reallocation.py','--out',copy/'economy/results','--panel',temp/'restored/extracted/research/sgrt_recovered_20261019/data/panel.parquet')
  script('full_fifteen_year_calendar','economy/build_multiyear_exact.py','--base',temp,'--out',copy/'economy/pinned_calendar');script('all_sector_calendar','economy/build_sector_calendar.py','--base',temp,'--out',copy/'economy/pinned_sector_calendar');script('crosscheck_calendars','economy/crosscheck_calendars.py','--root',copy/'economy')
  script('address_lifecycle','economy/audit_addresses.py','--base',temp,'--out',copy/'economy/address_audit_2021_2025');script('alias_examples','economy/build_alias_cases.py','--base',temp)
  script('provider_annual_profiles','model/join_annual_profiles.py','--input',copy/'economy/pinned_calendar/point_exact_code_witnesses_2011_2025.parquet','--out',copy/'model/annual_results')
  coverage=pd.read_csv(copy/'economy/pinned_calendar/coverage_2011_2025.csv');assert len(coverage)==15 and int(coverage.source_rows.sum())==63308662
  report['calendar_source_rows_actually_recomputed']=int(coverage.source_rows.sum());report['calendar_years_recomputed']=coverage.year.tolist()
  # Compare actual tables, not logs/JSON absolute paths, timestamps or binaries.
  for generated in sorted(copy.rglob('*')):
   if not generated.is_file() or not generated.name.endswith(('.csv','.csv.gz','.parquet')):continue
   rel=generated.relative_to(copy)
   if len(rel.parts)==1:continue
   if any(part in {'raw','captures','sources','remote_selected','remote_address_selected','national_sources','literature_review'} for part in rel.parts):continue
   original=ROOT/rel
   if not original.is_file():continue
   if generated.suffix=='.parquet':
    lefts=(x.to_pandas() for x in pq.ParquetFile(original).iter_batches(batch_size=50000));rights=(x.to_pandas() for x in pq.ParquetFile(generated).iter_batches(batch_size=50000))
   else:lefts=pd.read_csv(original,low_memory=False,chunksize=50000);rights=pd.read_csv(generated,low_memory=False,chunksize=50000)
   result={'table':str(rel),'original_shape':[0,0],'replay_shape':[0,0],'original_sha256':sha(original),'replay_sha256':sha(generated),'numeric_rtol':1e-12,'numeric_atol':1e-10,'comparison_chunk_rows':50000,'pass':True}
   try:
    for left,right in itertools.zip_longest(lefts,rights):
     assert left is not None and right is not None,'Different number of chunks'
     result['original_shape'][0]+=len(left);result['replay_shape'][0]+=len(right);result['original_shape'][1]=left.shape[1];result['replay_shape'][1]=right.shape[1]
     pd.testing.assert_frame_equal(left.reset_index(drop=True),right.reset_index(drop=True),check_dtype=False,check_exact=False,rtol=1e-12,atol=1e-10)
   except AssertionError as exc:result['pass']=False;result['difference']=str(exc)[:3000]
   report['comparisons'].append(result)
  changed=[path for path,digest in frozen.items() if sha(Path(path))!=digest];report['frozen_input_files_changed']=changed;assert not changed
  report['tables_compared']=len(report['comparisons']);report['all_compared_tables_match']=all(x['pass'] for x in report['comparisons']);assert report['all_compared_tables_match']
  report['status']='PASS'
 except Exception as exc:
  report['status']='FAIL';report['error']=repr(exc)
 finally:
  report['seconds']=round(time.time()-t,3);report['finished_utc']=datetime.datetime.now(datetime.timezone.utc).isoformat();dump(a.receipt,report)
  for fd in fds:os.close(fd)
 print(json.dumps({'status':report['status'],'commands':len(report['commands']),'tables_compared':report.get('tables_compared'),'seconds':report['seconds'],'receipt':str(a.receipt)},ensure_ascii=False),flush=True)
 if report['status']!='PASS':raise SystemExit(1)
if __name__=='__main__':main()
